            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">What is it?</h5>
            <p style="margin:0 0 16px;">A check that a specific job was done the way the written process says it should be, not to be confused with a QMS Audit. Process Audits are carried out against the process flow charts: someone from your own business (the internal auditor) reviews the work, then records what they found.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Why does it matter?</h5>
            <p style="margin:0 0 16px;">Writing a process down is easy. Showing that people actually follow it is the hard part, and it is the part auditors care about most. Because your audit is done remotely, these records are the evidence if this list is empty, the auditor has nothing to look at.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Basic steps</h5>
            <ul style="margin:0;padding-inline-start:18px;list-style:disc;color:var(--am-text);font-size:13.5px;line-height:1.5;">
                <li style="margin-bottom:6px;">Click Add Process Audit.</li>
                <li style="margin-bottom:6px;">Choose which process or work instruction you checked, for example QP1 Sales Process.</li>
                <li style="margin-bottom:6px;">Enter who carried out the audit and the date.</li>
                <li style="margin-bottom:6px;">Record what you found: anything wrong, anything worth noting, and what will be done about it.</li>
                <li style="margin-bottom:6px;">Attach photos or completed forms the remote auditor can open these.</li>
                <li>Set how often this audit should be repeated.</li>
            </ul>
