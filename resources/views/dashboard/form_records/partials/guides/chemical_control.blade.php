            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">What is it?</h5>
            <p style="margin:0 0 16px;">A log of every hazardous substance used in your workplace, cleaning products, fuels, solvents, adhesives, paints showing where it is kept and what it is used for. COSHH stands for Control of Substances Hazardous to Health.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Why does it matter?</h5>
            <p style="margin:0 0 16px;">People are harmed by substances they did not know were dangerous. This log makes sure anyone can find out what they are handling. It is also a legal requirement in most countries, and a health and safety auditor will ask for it..</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Basic steps</h5>
            <ul style="margin:0;padding-inline-start:18px;list-style:disc;color:var(--am-text);font-size:13.5px;line-height:1.5;">
                <li style="margin-bottom:6px;">Walk round and note every chemical &amp; hazardous material in use.</li>
                <li style="margin-bottom:6px;">Click Add COSHH for each one.</li>
                <li style="margin-bottom:6px;">Record the chemical name, where it is stored, and what it is used for.</li>
                <li style="margin-bottom:6px;">Set the status: in use, or no longer used.</li>
                <li style="margin-bottom:6px;">Keep the safety data sheet from the supplier alongside the record.</li>
                <li>Review the list once a year, and whenever a new product is brought into the workplace.</li>
