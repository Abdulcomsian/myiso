                <li style="margin-bottom:6px;">Click Add Supplier.</li>
                <li style="margin-bottom:6px;">Enter the company name, address, country, phone and email.</li>
                <li style="margin-bottom:6px;">Describe what they supply in a few words.</li>
                <li style="margin-bottom:6px;">Review how each supplier is performing at regular intervals and record the outcome.</li>
                <li style="margin-bottom:6px;">Raise a Non-Conformity whenever a supplier causes a problem, so there is a record behind any decision to stop using them.</li>
                <li>Review periodically for supplier trends and take urgent action if needed, and review annually at Management Reviews.</li>
