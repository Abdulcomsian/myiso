            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">What is it?</h5>
            <p style="margin:0 0 16px;">A register of the businesses you buy goods or services from, with their contact details and what they supply. It is how Supplier Reviews are able to be graded.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Why does it matter?</h5>
            <p style="margin:0 0 16px;">If a supplier lets you down, your customer feels it. The standard expects you to choose suppliers on evidence and keep an eye on how they perform. An auditor will ask how you decide a supplier is good enough, this register is where you prove it.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Basic steps</h5>
