            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">What is it?</h5>
            <p style="margin:0 0 16px;">A written think-through of the things that could hurt someone, what could happen, how likely it is, how bad it would be, and what you are doing to make it less likely. Not to be confused with “Risk Assesments’</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Why does it matter?</h5>
            <p style="margin:0 0 16px;">Risk is scored twice here on purpose. The first score is the risk before you do anything; the second is the risk once your controls are in place. The gap between the two is your proof that the safety measures actually work, and that is exactly what an auditor is looking for.</p>

            <h5 style="font-size:13px;font-weight:600;color:var(--am-primary);margin:0 0 6px;">Basic steps</h5>
            <ul style="margin:0;padding-inline-start:18px;list-style:disc;color:var(--am-text);font-size:13.5px;line-height:1.5;">
                <li style="margin-bottom:6px;">Click Add Assessment.</li>
                <li style="margin-bottom:6px;">Describe the scenario, what could go wrong, and to whom.</li>
                <li style="margin-bottom:6px;">Score the initial risk: how likely it is, multiplied by how serious it would be.</li>
                <li style="margin-bottom:6px;">Write down the prevention measures you have put in place.</li>
                <li style="margin-bottom:6px;">Score the revised risk, with those measures working.</li>
                <li>Review it after any incident, after any change to how the work is done, and at least once a year.</li>
            </ul>
